import assert from 'node:assert/strict';
import {
  lotteryDuration,lotteryProgress,lotteryReplayProgress,lotteryCountdownClock,
  LOTTERY_PRE_SHOW_MS,LOTTERY_CURTAIN_OPEN_MS,LOTTERY_FINAL_COUNTDOWN_MS,
  LOTTERY_CEREMONY_MS,LOTTERY_INTRO_MS,LOTTERY_MIX_MS,
  LOTTERY_ROLL_MS,LOTTERY_ANNOUNCEMENT_MS
} from '../src/lottery-timing.js';
const begin='2026-10-25T19:00:00.000Z';
const at=ms=>lotteryProgress(12,begin,Date.parse(begin)+ms);
assert.deepEqual([
  LOTTERY_PRE_SHOW_MS,LOTTERY_CURTAIN_OPEN_MS,LOTTERY_FINAL_COUNTDOWN_MS,
  LOTTERY_INTRO_MS,LOTTERY_MIX_MS,LOTTERY_ROLL_MS,LOTTERY_ANNOUNCEMENT_MS
],[300000,2000,3000,10000,10000,3200,5000]);
assert.equal(LOTTERY_CEREMONY_MS,5000);
assert.equal(at(-300001).phase,'waiting');
assert.equal(at(-300000).phase,'countdown','5-minute clock appears at exactly five minutes to go');
assert.equal(at(-300000).secondsToNext,300);
assert.equal(lotteryCountdownClock(at(-300000).secondsToNext),'05:00');
assert.equal(lotteryCountdownClock(at(-299000).secondsToNext),'04:59');
assert.equal(lotteryCountdownClock(at(-1000).secondsToNext),'00:01');
assert.equal(at(-1).phase,'countdown');
assert.equal(at(-1).revealed,0);
assert.equal(at(0).phase,'curtain-opening');
assert.equal(at(0).phaseElapsedMs,0);
assert.equal(at(1999).phase,'curtain-opening');
assert.equal(at(2000).phase,'final-countdown');
assert.equal(at(2000).secondsToNext,3);
assert.equal(at(3000).secondsToNext,2);
assert.equal(at(4000).secondsToNext,1);
assert.equal(at(4999).phase,'final-countdown');
assert.equal(at(4999).revealed,0);
assert.equal(at(5000).phase,'intro','first ten-second drum mix starts after the visible 3-2-1');
assert.equal(at(5000).secondsToNext,10);
assert.equal(at(14999).phase,'intro');
assert.equal(at(14999).secondsToNext,1);
assert.equal(at(15000).phase,'rolling');
assert.equal(at(15000).revealed,1);
assert.equal(at(18199).phase,'rolling');
assert.equal(at(18200).phase,'announce');
assert.equal(at(23199).phase,'announce');
assert.equal(at(23200).phase,'mixing');
assert.equal(at(23200).secondsToNext,10);
assert.equal(at(33199).phase,'mixing');
assert.equal(at(33200).phase,'rolling');
assert.equal(at(33200).revealed,2);
assert.equal(at(36400).phase,'announce');
assert.equal(at(41400).phase,'mixing');
assert.equal(at(41400).revealed,2);
// Official draw order is generated by the backend at lottery time; the
// presentation must work during all five minutes before any order exists.
const noOrder=ms=>lotteryProgress(0,begin,Date.parse(begin)+ms);
assert.equal(noOrder(-300000).phase,'countdown');
assert.equal(noOrder(0).phase,'curtain-opening');
assert.equal(noOrder(2000).phase,'final-countdown');
assert.equal(noOrder(5000).phase,'awaiting-order');
assert.equal(noOrder(5000).revealed,0);
for(let ms=-300000;ms<lotteryDuration(12)+1000;ms+=1019){
  assert.deepEqual(at(ms),lotteryProgress(12,begin,Date.parse(begin)+ms),
    'late joiners recover exact stage and ball from server time');
}
let previousMix=-1,previousAnnounce=-1,previousRoll=-1;
for(let ms=0;ms<lotteryDuration(12);ms+=100){
  const p=at(ms);
  assert(p.revealed>=0&&p.revealed<=12);
  if(p.phase==='mixing'&&previousMix!==p.ballNumber){
    assert.equal(p.revealed,p.ballNumber-1);
    previousMix=p.ballNumber;
  }
  if(p.phase==='rolling'&&previousRoll!==p.ballNumber){
    previousRoll=p.ballNumber;
    assert.equal(p.revealed,p.ballNumber);
  }
  if(p.phase==='announce')previousAnnounce=p.ballNumber;
}
assert.equal(previousRoll,12);
assert.equal(previousAnnounce,12);
assert.equal(at(lotteryDuration(12)-1).phase,'announce');
assert.equal(at(lotteryDuration(12)).phase,'complete');
assert.equal(at(lotteryDuration(12)).revealed,12);
assert.equal(lotteryProgress(12,null,Date.now()).phase,'complete');
assert.equal(lotteryProgress(0,null,Date.now()).phase,'waiting');
const halfway=lotteryDuration(12)/2;
assert.deepEqual(at(halfway),lotteryProgress(12,begin,Date.parse(begin)+halfway));
assert.notEqual(at(halfway).phase,'intro');
const officialResults=Object.freeze([
 'team7','team3','team1','team10','team6','team12',
 'team4','team2','team8','team11','team5','team9'
]);
const unchangedOfficialOrder=officialResults.join('|');
assert.equal(lotteryReplayProgress(12,0).phase,'curtain-opening');
assert.equal(lotteryReplayProgress(12,2000).phase,'final-countdown');
assert.equal(lotteryReplayProgress(12,5000).phase,'intro');
assert.equal(lotteryReplayProgress(12,15000).phase,'rolling');
assert.equal(lotteryReplayProgress(12,lotteryDuration(12)).phase,'complete');
assert.equal(at(lotteryDuration(12)+20000).phase,'complete');
assert.equal(officialResults.join('|'),unchangedOfficialOrder,'replay cannot change official lottery order');
console.log('PASS: closed curtain + 5-minute clock, synchronized opening and 3-2-1, mix/draw, late join, saved-order replay');
