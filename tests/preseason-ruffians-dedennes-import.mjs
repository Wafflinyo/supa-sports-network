import assert from 'node:assert/strict';
import {preseasonGames,preseasonPlayerStatsForGame,preseasonPlayerStats,preseasonTeamStats} from '../src/preseason-game-data.js';

const match=preseasonGames.find(game=>game.gameId==='PSR1 Ruffians @ Dedennes');
assert.ok(match,'The original Ruffians @ Dedennes game must be imported');
assert.equal(match.away,'Rogueport Ruffians');
assert.equal(match.home,'Decalburg Dedennes');
assert.equal(match.awayScore,4);
assert.equal(match.homeScore,0);
assert.equal(match.mvp,4,'Winning-team MVP: Diddy Kong');
const scores=preseasonPlayerStatsForGame(match);
assert.equal(scores.length,18,'The entire nine-player lineup on each team must appear');
assert.equal(new Set(scores.map(row=>row.playerId)).size,18);
const value=id=>scores.find(row=>row.playerId===id)?.stats;
assert.equal(value(4)?.gameScore,77.5,'Diddy Kong includes pitching, MVP, Item and complete-game points');
assert.equal(value(4)?.completeGames,1);
assert.equal(value(13)?.gameScore,-8,'Negative player Game Scores are retained');
assert.equal(value(87)?.gameScore,47.67,'Brock is linked to Green Mii (M) pitching stats');
assert.equal(value(87)?.battersFaced,16);
assert.equal(value(154)?.gameScore,48.33);
const points=team=>Math.round(scores.filter(p=>p.teamName===team).reduce((sum,p)=>sum+p.stats.tgp,0)*100)/100;
assert.equal(points(match.away),424.5);
assert.equal(points(match.home),300);
const teams=preseasonTeamStats();
const away=teams.find(row=>row.teamName===match.away);
const home=teams.find(row=>row.teamName===match.home);
assert.ok(away&&home);
assert.equal(away.stats.tgp,424.5);
assert.equal(home.stats.tgp,300);
assert.equal(away.stats.runsScored,4);
assert.equal(home.stats.runsScored,0);
const players=preseasonPlayerStats();
assert.equal(players.find(p=>p.playerId===4)?.stats.gameScore,77.5);
assert.equal(players.find(p=>p.playerId===13)?.stats.gameScore,-8);
assert.ok(preseasonGames.some(p=>p.gameId==='PSR1 Fuggetaboudits @ Tanks'));
assert.ok(preseasonGames.some(p=>p.gameId==='PSR1 Checkers @ Pangolins'));
console.log('Ruffians @ Dedennes: verified 18 player scores, categories and team totals.');
